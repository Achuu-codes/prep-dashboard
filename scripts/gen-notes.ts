/**
 * Generates src/content/notes.generated.ts — a static map from note slug to a
 * dynamic import of its MDX file.
 *
 * A static map is used rather than a template-literal import because Turbopack
 * resolves dynamic imports at build time and cannot follow a variable path.
 * Run this after adding or renaming an MDX note.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { log } from './_bootstrap';

const SECTIONS = ['dsa'];
const OUT = resolve(process.cwd(), 'src/content/notes.generated.ts');

function main() {
  const lines: string[] = [];
  let count = 0;

  for (const section of SECTIONS) {
    const dir = resolve(process.cwd(), 'content', section);
    let files: string[] = [];
    try {
      files = readdirSync(dir).filter((f) => f.endsWith('.mdx')).sort();
    } catch {
      log.warn(`content/${section} does not exist yet`);
      continue;
    }
    for (const file of files) {
      const slug = file.replace(/\.mdx$/, '');
      lines.push(
        `  '${section}/${slug}': () => import('@content/${section}/${file}'),`,
      );
      count++;
    }
  }

  const body = `/* AUTO-GENERATED by \`npm run notes\`. Do not edit by hand. */
import type { MDXProps } from 'mdx/types';

export type NoteModule = {
  default: (props: MDXProps) => React.JSX.Element;
};

/** "<section>/<noteSlug>" -> dynamic import of that MDX note. */
export const notes: Record<string, () => Promise<NoteModule>> = {
${lines.join('\n')}
};

export function hasNote(section: string, slug: string | null): boolean {
  return Boolean(slug && \`\${section}/\${slug}\` in notes);
}

export async function loadNote(section: string, slug: string | null) {
  if (!slug) return null;
  const loader = notes[\`\${section}/\${slug}\`];
  if (!loader) return null;
  return (await loader()).default;
}
`;

  writeFileSync(OUT, body);
  log.ok(`notes.generated.ts: ${count} note${count === 1 ? '' : 's'}`);
}

main();
